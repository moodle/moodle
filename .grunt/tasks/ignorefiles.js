module.exports = grunt => {

    /**
     * Generate the PHPCS configuration.
     *
     * @param {Object} thirdPartyPaths
     */
    const phpcsIgnore = (thirdPartyPaths) => {
        const {toXML} = require('jstoxml');

        const config = {
            _name: 'ruleset',
            _attrs: {
                name: "MoodleCore",
            },
            _content: [
                {
                    rule: {
                        _attrs: {
                            ref: './phpcs.xml.dist',
                        },
                    },
                },
            ],
        };

        thirdPartyPaths.forEach(library => {
            config._content.push({
                'exclude-pattern': library,
            });
        });

        grunt.file.write('phpcs.xml', toXML(config, {
            header: true,
            indent: '  ',
        }) + "\n");
    };

    /**
     * Generate ignore files (utilising thirdpartylibs.xml data)
     */
    const handler = function() {
        const path = require('path');
        const ComponentList = require(path.join(process.cwd(), '.grunt', 'components.js'));

        // An array of paths to third party directories.
        const thirdPartyPaths = ComponentList.getThirdPartyPaths();
        const localStylelintIgnorePaths = ComponentList.getLocalIgnorePaths('.stylelintignore');
        const localEslintIgnorePaths = ComponentList.getLocalIgnorePaths('.eslintignore');

        // Generate .eslintignores.json, which .eslintrc extends.
        //
        // These are ignorePatterns rather than an .eslintignore file because XO bundles
        // ESLint 10, which warns on every run that .eslintignore is no longer supported.
        // ESLint 8 reads them from the extended config just the same.
        const eslintIgnores = [
            // Do not ignore the .grunt directory.
            '!/.grunt',

            // Ignore all yui/src meta directories and build directories.
            '*/**/yui/src/*/meta/',
            '*/**/build/',

            // TypeScript is linted by XO ("grunt xo"), which brings its own parser.
            // ESLint has none configured for it and would fail to parse these files.
            '*.ts',
            '*.tsx',
        ].concat(thirdPartyPaths).concat(localEslintIgnorePaths);
        grunt.file.write('.eslintignores.json', JSON.stringify({
            ignorePatterns: eslintIgnores,
        }, null, '  ') + '\n');

        // Older branches generated .eslintignore here. Left behind, it makes XO warn on every run.
        if (grunt.file.exists('.eslintignore')) {
            grunt.file.delete('.eslintignore');
        }

        // Generate .stylelintignore.
        const stylelintIgnores = [
            '# Generated by "grunt ignorefiles"',
            '**/yui/build/*',
            'public/theme/boost/style/moodle.css',
            'jsdoc/styles/*.css',
            'public/admin/tool/componentlibrary/hugo/dist/css/docs.css',
        ].concat(thirdPartyPaths).concat(localStylelintIgnorePaths);
        grunt.file.write('.stylelintignore', stylelintIgnores.join('\n') + '\n');

        phpcsIgnore(thirdPartyPaths);
    };

    grunt.registerTask('ignorefiles', 'Generate ignore files for linters', handler);

    return handler;
};
