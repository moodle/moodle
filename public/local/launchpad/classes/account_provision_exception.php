namespace local_launchpad;

/**
 * Rejected or invalid account provisioning / role-grant operation.
 *
 * @package    local_launchpad
 * @copyright  2026 IntelliVerse-X
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
final class account_provision_exception extends \InvalidArgumentException {

    /** Machine-readable reason (e.g. forbidden_grant_admin). */
    public readonly string $errorcode;

    public function __construct(string $errorcode, string $message = '') {
        $this->errorcode = $errorcode;
        parent::__construct($errorcode . ($message !== '' ? (': ' . $message) : ''));
    }
}
